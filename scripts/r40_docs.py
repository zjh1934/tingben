from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def sub(rel, pairs):
    p = ROOT / rel
    s = p.read_text(encoding="utf-8")
    for a, b in pairs:
        if a not in s:
            raise SystemExit("未命中，停止: %s | %s" % (rel, a[:60]))
        s = s.replace(a, b, 1)
    p.write_text(s, encoding="utf-8")
    print("更新", rel)


def append(rel, text):
    p = ROOT / rel
    with p.open("a", encoding="utf-8") as f:
        f.write(text)
    print("追加", rel)


